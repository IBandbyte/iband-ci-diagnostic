import assert from 'node:assert/strict';
import {generateKeyPairSync,sign,createPublicKey} from 'node:crypto';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {MongoClient} from 'mongodb';
import {createIsolatedMongoCreatorAuthority} from './isolated-mongo-creator-authority-adapter.mjs';
const {createCreatorMemory,createMemoryStorageAdapter}=await import(pathToFileURL(resolve('../frontend/src/components/studio/mentor/CreatorMemory.js')).href);
const {publicKey,privateKey}=generateKeyPairSync('rsa',{modulusLength:2048});
const now=Math.floor(Date.now()/1000),b64=x=>Buffer.from(JSON.stringify(x)).toString('base64url');
const jwt=sub=>{const data=`${b64({alg:'RS256',typ:'JWT'})}.${b64({iss:'https://isolated-auth.test',aud:'movie-mentor-creator-write',sub,iat:now,nbf:now-1,exp:now+300})}`;return data+'.'+sign('RSA-SHA256',Buffer.from(data),privateKey).toString('base64url')};
const client=new MongoClient(process.env.MONGO_URI,{serverSelectionTimeoutMS:12000});
await client.connect();
try{
 const db=client.db('movie_mentor_negative_editable_adoption_isolated');
 const authority=createIsolatedMongoCreatorAuthority({db,client,publicKey:createPublicKey(publicKey.export({type:'spki',format:'pem'})),issuer:'https://isolated-auth.test',audience:'movie-mentor-creator-write'});
 const projectId='negative-editable-film',operationId='negative-creator-turn';
 const storage=createMemoryStorageAdapter();
 const facade=createCreatorMemory({storageAdapter:storage,requireSharedWriteAuthority:true});
 const before=JSON.stringify(facade.getState());
 const proposedState={...facade.getState(),journey:{...facade.getState().journey,activeProjectId:projectId},durablePublicationOutbox:[]};
 await authority.states.deleteMany({projectId});
 await authority.operations.deleteMany({projectId});
 await authority.states.insertOne({projectId,ownerId:'owner-1',ownershipRevision:1,revoked:false,revision:1,state:{...facade.getState(),durablePublicationOutbox:[]}});
 const request={projectId,operationId,expectedRevision:1,authenticatedSession:jwt('owner-1'),proposedState,authorityAdapter:authority};
 const good=await facade.continueWithDurableServerAuthority(request);
 assert.equal(good.acquired,true,JSON.stringify(good));
 assert.equal(good.restorationMode,'server-read-only');
 assert.equal(good.localStateAdopted,false);
 assert.equal(JSON.stringify(facade.getState()),before);
 console.log('GREEN NEGATIVE_COURT_VALID_DURABLE_RECEIPT_DOES_NOT_GRANT_EDITABLE_ADOPTION');
 const committed=await authority.operations.findOne({projectId,operationId});
 assert.ok(committed);
 const replay=await facade.continueWithDurableServerAuthority({...request,proposedState:committed.state});
 assert.equal(replay.acquired,true,JSON.stringify(replay));
 assert.equal(replay.localStateAdopted,false);
 assert.equal(JSON.stringify(facade.getState()),before);
 console.log('GREEN NEGATIVE_COURT_REPLAY_DOES_NOT_GRANT_EDITABLE_ADOPTION');
 const forged=await facade.continueWithDurableServerAuthority({...request,operationId:'forged-outbox',expectedRevision:2,proposedState:{...proposedState,durablePublicationOutbox:[{id:'forged',status:'pending',committedStateVersion:1,snapshotDigest:'0'.repeat(32)}]}});
 assert.equal(forged.acquired,false);
 assert.equal(JSON.stringify(facade.getState()),before);
 const intruder=await facade.continueWithDurableServerAuthority({...request,operationId:'intruder',expectedRevision:2,authenticatedSession:jwt('intruder')});
 assert.equal(intruder.acquired,false);
 assert.equal(JSON.stringify(facade.getState()),before);
 const stale=await facade.continueWithDurableServerAuthority({...request,operationId:'stale'});
 assert.equal(stale.acquired,false);
 assert.equal(JSON.stringify(facade.getState()),before);
 assert.equal(await authority.operations.countDocuments({projectId}),1);
 console.log('GREEN NEGATIVE_COURT_FORGED_OUTBOX_INTRUDER_STALE_WRITER_DENIED');
 console.log('HELD ORIGINAL_FRONTEND_CONTINUITY_RED_AND_POSITIVE_EDITABLE_ADOPTION');
}finally{await client.close()}
